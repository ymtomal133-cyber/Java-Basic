public class VowelConsonant {
    public static void main(String[] args) {
        
        char ch = 'j';

        if(ch == 'a' || ch == 'e' || ch == 'i' || ch == 'o' || ch == 'u'){
            System.out.println(ch + " Vowel.");
        } else {
            System.out.println(ch + " Consonant.");
        }
    }
}
